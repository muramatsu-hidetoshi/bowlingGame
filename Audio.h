
/*==========================================================================
音声再生・管理 [audio.h]

概要：
    XAudio2を使用した音声再生機能を提供する。
    音声システムの初期化、音声ファイルの読み込み、再生、
    および読み込んだ音声データの解放を行う。

主な機能：
    ・音声システムの初期化と終了
    ・音声ファイルの読み込み
    ・読み込んだ音声データの解放
    ・音声の再生およびループ再生

==========================================================================*/

#pragma once

//==========================================================================
// 音声システム管理
//==========================================================================

// 音声システムを初期化する。
void InitAudio();

// 音声システムを終了し、使用しているリソースを解放する。
void UninitAudio();


//==========================================================================
// 音声データ管理
//==========================================================================

// 音声ファイルを読み込む。
// 引数：FileName - 読み込む音声ファイルのパス
// 戻り値：音声データの管理番号。読み込み可能な領域がない場合は -1。
int LoadAudio(const char* FileName);

// 指定した管理番号の音声データを解放する。
// 引数：Index - 解放する音声データの管理番号
void UnloadAudio(int Index);


//==========================================================================
// 音声再生
//==========================================================================

// 指定した音声データを再生する。
// 引数：Index - 再生する音声データの管理番号
//       Loop  - trueの場合はループ再生、falseの場合は通常再生
void PlayAudio(int Index, bool Loop = false);