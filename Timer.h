
/*==========================================================================
ゲーム内のタイマー管理 [timer.h]

タイマーの初期化、更新、描画、終了処理を宣言する。
==========================================================================*/

#pragma once

// タイマーの初期化
// x      : タイマーの表示位置（X座標）
// y      : タイマーの表示位置（Y座標）
// digit  : 表示する桁数
void Timer_Initilize(float x, float y, int digit);

// 経過時間に応じてタイマーを更新する
// elapsed_time : 前回の更新からの経過時間（秒）
void Timer_Update(double elapsed_time);

// タイマーを描画する
void Timer_Draw();

// タイマーの終了処理
void Timer_Finalize();
